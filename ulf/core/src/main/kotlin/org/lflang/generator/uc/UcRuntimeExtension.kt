package org.lflang.generator.uc

import org.lflang.generator.uc.UcModeGenerator.Companion.usesModes
import org.lflang.lf.Reactor

/**
 * Build-time contribution made by a statically wired Reactor-UC runtime extension.
 *
 * The runtime calls an extension through the `LF_EXTENSION_ON_*` macros of a configuration header
 * the program supplies, see [UcRuntimeExtensions.generateConfigHeader]. This model owns that wiring
 * and the generated project's source embedding, for both build systems a generated project ships:
 * the CMakeLists and the Makefile beside it.
 */
data class UcRuntimeExtension(
    val id: String,
    /**
     * Variable naming this extension's location. Read from the environment to find a checkout to
     * embed, and set by both generated build files to the embedded copy.
     */
    val pathVariable: String,
    /** Directory the copy is embedded under, inside the generated project. */
    val embeddedDirectory: String,
    /** Entries copied out of the extension's checkout into that directory. */
    val artifacts: List<String>,
    /**
     * Header declaring the extension's hook functions, relative to [embeddedDirectory]. It must be
     * a leaf header, since the runtime includes it before its core types are complete.
     */
    val hooksHeader: String,
    /** The function implementing each runtime hook the extension takes part in. */
    val hooks: Map<UcExtensionHook, String>,
    /** Namespaced CMake target the generated program links. */
    val cmakeTarget: String,
    /**
     * Make fragment, relative to [embeddedDirectory], declaring the sources, include directories
     * and compile definitions a Makefile-driven platform needs. It is the Make counterpart of the
     * extension's CMakeLists, and the extension owns it.
     */
    val makeFragment: String,
)

/**
 * The runtime hooks an extension can implement, with the parameters of their `LF_EXTENSION_ON_*`
 * macro. The context always comes first. [fallback] is what the hook evaluates to while no context
 * is bound.
 */
enum class UcExtensionHook(val params: List<String>, val fallback: String) {
  TAG_START(listOf("Context", "Env", "Tag", "Shutdown"), "(void)0"),
  TAG_COMPLETE(listOf("Context", "Env", "Tag", "Shutdown"), "(void)0"),
  NEXT_TAG(listOf("Context", "Env", "Tag"), "FOREVER_TAG"),
  SHUTDOWN(listOf("Context", "Env"), "(void)0"),
}

object UcRuntimeExtensions {
  /** The configuration header every program using an extension gets, in its src-gen root. */
  const val CONFIG_HEADER = "lf_extensions.h"

  val micromode =
      UcRuntimeExtension(
          id = "micromode",
          pathVariable = "MICROMODE_PATH",
          embeddedDirectory = "micromode",
          artifacts = listOf("src", "include", "CMakeLists.txt", "micromode.mk"),
          hooksHeader = "include/micromode/hooks.h",
          hooks =
              mapOf(
                  UcExtensionHook.TAG_START to "lf_micromode_on_tag_start",
                  UcExtensionHook.TAG_COMPLETE to "lf_micromode_on_tag_complete",
                  UcExtensionHook.NEXT_TAG to "lf_micromode_on_next_tag",
                  UcExtensionHook.SHUTDOWN to "lf_micromode_on_shutdown",
              ),
          cmakeTarget = "micromode::micromode",
          makeFragment = "micromode.mk",
      )

  fun requiredBy(reactor: Reactor): List<UcRuntimeExtension> =
      if (reactor.usesModes) listOf(micromode) else emptyList()

  /**
   * The header named by `LF_EXTENSION_CONFIG_HEADER`, routing the runtime's hooks to [extension].
   *
   * The bound context goes to the extension as it is: micromode is the only extension, so its
   * program is the whole context. Combining two extensions would need an aggregate context.
   *
   * A hook does nothing while no context is bound. A generated program binds one before it starts,
   * but the LF tests share one runtime between modal programs and programs that bind nothing.
   *
   * The hooks header is included by a path relative to this one, since the runtime is not given the
   * extension's include directory.
   */
  fun generateConfigHeader(extension: UcRuntimeExtension): String {
    val hooks =
        extension.hooks.entries.joinToString("\n") { (hook, function) ->
          val params = hook.params.joinToString(", ")
          val args = hook.params.joinToString(", ") { "($it)" }
          "#define LF_EXTENSION_ON_${hook.name}($params) \\\n" +
              "  ((Context) != NULL ? $function($args) : ${hook.fallback})"
        }
    return """
        |/* Runtime extension wiring of this program, generated by ulfc. The runtime includes it
        | * while its core types are still incomplete, so it only declares. */
        |#ifndef LF_EXTENSIONS_H
        |#define LF_EXTENSIONS_H
        |
        |#include "${extension.embeddedDirectory}/${extension.hooksHeader}"
        |
        |$hooks
        |
        |#endif
        |"""
        .trimMargin()
  }
}
